function escapePublicationHtml(value) {

  return String(value ?? '')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#039;');

}



function sortedPublications() {

  return publicationsData
    .map((publication, index) => ({
      ...publication,
      originalIndex: index
    }))
    .sort((a, b) => {

      const dateA =
        new Date(a.date || `${a.year}-01-01`);

      const dateB =
        new Date(b.date || `${b.year}-01-01`);


      if (dateB - dateA !== 0) {

        return dateB - dateA;

      }


      return a.originalIndex -
             b.originalIndex;

    });

}



/* =========================================================
   HOME — LATEST PUBLICATIONS
   ========================================================= */

function renderRecentPublications(
  containerId = 'recentPublications',
  limit = 5
) {

  const container =
    document.getElementById(containerId);


  if (!container) return;


  const publications =
    sortedPublications().slice(0, limit);


  container.innerHTML =
    publications.map(publication => `

      <article class="home-publication-item">

        <h3 class="home-publication-title">
          ${escapePublicationHtml(publication.title)}
        </h3>


        <p class="home-publication-meta">
          ${escapePublicationHtml(publication.authors)}
          ·
          ${escapePublicationHtml(publication.venue)}
        </p>


        ${
          publication.url

            ? `
              <a
                class="home-publication-link"
                href="${escapePublicationHtml(publication.url)}"
                target="_blank"
                rel="noopener noreferrer"
              >
                View publication &#8599;
              </a>
            `

            : ''
        }

      </article>

    `).join('');

}



/* =========================================================
   PUBLICATIONS PAGE — ALL PUBLICATIONS
   ========================================================= */

function renderAllPublications(
  containerId = 'allPublications'
) {

  const container =
    document.getElementById(containerId);


  if (!container) return;


  const publications =
    sortedPublications();


  const years =
    [...new Set(
      publications.map(
        publication => publication.year
      )
    )];


  container.innerHTML =
    years.map(year => {

      const yearPublications =
        publications.filter(
          publication =>
            publication.year === year
        );


      return `

        <section
          class="pub-year-section"
          id="year-${escapePublicationHtml(year)}"
        >

          <h2 class="pub-year">
            ${escapePublicationHtml(year)}
          </h2>


          <a
            href="#top"
            class="back-to-top"
          >
            [back to top]
          </a>


          <div class="pub-list">

            ${
              yearPublications.map(publication => `

                <article class="pub-card">

                  <h3 class="pub-card-title">
                    ${escapePublicationHtml(publication.title)}
                  </h3>


                  <p class="pub-authors">
                    ${escapePublicationHtml(publication.authors)}
                  </p>


                  <p class="pub-venue">
                    ${escapePublicationHtml(publication.venue)}
                  </p>


                  ${
                    publication.type

                      ? `
                        <div class="pub-type">
                          ${escapePublicationHtml(publication.type)}
                        </div>
                      `

                      : ''
                  }


                  ${
                    publication.url

                      ? `
                        <p class="pub-links">

                          <a
                            class="pub-link"
                            href="${escapePublicationHtml(publication.url)}"
                            target="_blank"
                            rel="noopener noreferrer"
                          >
                            Paper
                          </a>

                        </p>
                      `

                      : ''
                  }

                </article>

              `).join('')
            }

          </div>

        </section>

      `;

    }).join('');

}
